"""Phase 6 Plan 06-02: unified standard-layer corpus integration.

Merges the Kaggle standard corpus (regenerated by Plan 06-01 to
``data/standard/kaggle/{race,entry,result}.parquet``) with the scraped standard
partitions (``data/standard/scraped/{YYYYMM}/{race,entry,result}.parquet``) into
a single unified ``data/standard/{race,entry,result}.parquet`` corpus per
CONTEXT.md D-03/D-04.

The integration is **idempotent** (HIGH #5): Kaggle is read from a SEPARATE
input path (``kaggle_input_dir``, default ``standard_dir / 'kaggle'``) that is
NEVER the output path. A second invocation against the same immutable inputs
produces byte-identical output. This makes the validate-before-swap
transactionality model below fully recoverable -- a mid-swap crash leaves at
worst a partial swap, but re-running ``integrate_standard_layer`` restores a
consistent corpus because the transform is deterministic and reads only from
its immutable inputs.

Transactionality model (HIGH #6 cycle-3 + cycle-5):
    1. Build all 3 merged DataFrames in memory.
    2. Validate integrity via ``validate_integrity`` (HIGH #8) and the
       extended hard-violation filter (HIGH #8b cycle-4).
    3. Stage all 3 to a per-run ``tempfile.mkdtemp`` directory via
       ``_atomic_write_parquet``.
    4. Validate each staged file (row count > 0, schema column-set, PK unique).
    5. Swap each staged file into root via ``_commit_staging`` (DEDICATED
       module-level function -- cycle-5). The swap is wrapped in try/finally
       that best-effort-removes the staging dir.

The 3 sequential ``os.replace`` calls INSIDE ``_commit_staging`` are not
perfectly atomic; a failure between the 2nd and 3rd swap leaves a partial swap.
However, because integration is idempotent (reads only from immutable inputs),
re-running ``integrate_standard_layer`` against the same inputs reproduces
identical output and fully recovers. This is the genuinely correct guarantee
for a deterministic transform -- more robust than backup-and-restore (which
depends on the backup surviving the crash).

Hard-violation filter (HIGH #8b cycle-4):
    ``validate_integrity`` returns the entry/result 1-to-1 mismatch violation
    as ``"horse_race_id mismatch: entry/result are not 1-to-1 ..."`` which
    contains NEITHER ``"duplicate"`` NOR ``"orphan"``. The Phase 4
    ``normalizer.py`` token filter therefore misses it. This module EXTENDS
    the filter to also match ``"mismatch"`` and ``"1-to-1"`` (belt-and-braces
    -- either substring matches the violation string), so a structurally
    inconsistent entry/result corpus is never silently written.

Load-bearing anti-patterns (Pitfalls from 06-RESEARCH.md / 06-PATTERNS.md):
    - Pitfall 5: SCHEMA_BY_TABLE is HARDCODED as {race, entry, result}; do NOT
      iterate ``TABLE_TO_SCHEMA.keys()`` (that superset includes the Phase 5
      tables excluded from the unified corpus per D-05).
    - Pitfall 6: pre-dedup overlap RAISES (not silent ``drop_duplicates``).
    - D-05: never add a ``source`` column (rows must be indistinguishable).
    - loguru per-TABLE logging only (MEMORY.md scraper-logging-no-per-item).
"""

from __future__ import annotations

import os
import shutil
import tempfile
from pathlib import Path

import pandas as pd
from loguru import logger
from pydantic import BaseModel

from src.schemas.audit import audit_leakage
from src.schemas.entry import EntrySchema
from src.schemas.race import RaceSchema
from src.schemas.result import ResultSchema
from src.scraper.normalizer import (
    _atomic_write_parquet,
    recast_to_canonical,
    validate_integrity,
)

# ---------------------------------------------------------------------------
# 3-table allowlist (Pitfall 5 / D-05 Phase-5-table protection)
# ---------------------------------------------------------------------------

#: Hardcoded 3-table allowlist. The Phase 5 tables (excluded from the unified
#: corpus per D-05) are deliberately NOT in this map; iterating
#: ``TABLE_TO_SCHEMA.keys()`` instead would overwrite the Phase 5 seed.
SCHEMA_BY_TABLE: dict[str, type[BaseModel]] = {
    "race": RaceSchema,
    "entry": EntrySchema,
    "result": ResultSchema,
}

#: Primary key per table. Used for pre-dedup overlap assertion (Pitfall 6).
PK_BY_TABLE: dict[str, str] = {
    "race": "race_id",
    "entry": "horse_race_id",
    "result": "horse_race_id",
}


# ---------------------------------------------------------------------------
# Helpers (reused from Phase 4 normalizer, NOT reimplemented)
#

# WR-04 (Phase 06 review): the local ``_recast_to_canonical`` definition was
# REMOVED in favor of the shared ``recast_to_canonical`` imported from
# ``src.scraper.normalizer``. The shared implementation uses COPY semantics
# (returns a new frame), which is the load-bearing behavior here: the callers
# at lines 285-286 invoke it on kaggle_df / scraped_df and rely on the
# originals being preserved for the audit call later. The back-compat alias
# keeps the underscore-prefixed name so existing references (and the
# ``__all__`` export) keep working.
# ---------------------------------------------------------------------------

_recast_to_canonical = recast_to_canonical


def _assert_column_set_equality(
    df: pd.DataFrame, schema: type[BaseModel], source_label: str
) -> None:
    """HIGH #9: column-set equality assert BEFORE reindex.

    ``pd.concat`` aligns on column names but takes the UNION of column sets,
    silently inflating the schema if one frame has an extra/dropped/renamed
    column. This guard refuses to reindex a frame whose column set diverges
    from ``schema.model_fields`` so the union can never silently grow.
    """
    expected = set(schema.model_fields.keys())
    actual = set(df.columns)
    if actual != expected:
        extra = actual - expected
        missing = expected - actual
        raise ValueError(
            f"{source_label}: column set mismatch "
            f"(extra={sorted(extra)}, missing={sorted(missing)}); "
            f"refusing to reindex"
        )


def _commit_staging(staging_dir: Path, standard_dir: Path) -> None:
    """Atomically-ish swap each staged table into the standard root.

    Performs exactly 3 ``os.replace`` calls (one per table in
    ``SCHEMA_BY_TABLE`` order). This function exists as a SEPARATE, PATCHABLE
    boundary so the transactionality regression test
    (``test_integration_partial_swap_recoverable``) can inject a mid-swap
    failure by monkeypatching THIS symbol -- NOT global ``os.replace``, which
    is also called by ``_atomic_write_parquet`` during the staging WRITES and
    would fire the monkeypatch at the wrong stage (cycle-4 NEW HIGH #2 fix).

    The 3 swaps are sequential, not atomic as a group. A failure between the
    2nd and 3rd swap leaves a partial swap (race swapped, entry/result not).
    Recovery is via idempotent re-run of ``integrate_standard_layer`` (HIGH #5
    + HIGH #6): the transform reads only from immutable inputs
    (``data/standard/kaggle/`` + scraped partitions), so re-running produces
    byte-identical output that fully restores the corpus.
    """
    for table in ("race", "entry", "result"):
        os.replace(
            staging_dir / f"{table}.parquet",
            standard_dir / f"{table}.parquet",
        )


