def integrate_standard_layer(
    standard_dir: Path = Path("data/standard"),
    kaggle_input_dir: Path | None = None,
) -> dict:
    """Merge Kaggle + scraped corpora into a unified standard-layer corpus.

    Parameters
    ----------
    standard_dir : pathlib.Path, default ``Path("data/standard")``
        Root standard directory. The output ``race``/``entry``/``result``
        Parquet are written here (D-03 -- overwrite, table-per-file per D-04).
        Scraped partitions are read from ``standard_dir / "scraped"``.
    kaggle_input_dir : pathlib.Path, optional
        SEPARATE Kaggle input path (HIGH #5 idempotency). Defaults to
        ``standard_dir / "kaggle"``. NEVER reads Kaggle from the output path.

    Returns
    -------
    dict
        ``{"race": Path, "entry": Path, "result": Path, "audit": {...}}``.
        The ``audit`` sub-dict records ``audit_leakage`` results per table.

    Raises
    ------
    FileNotFoundError
        If any Kaggle input Parquet is missing, or a scraped month directory
        lacks one of the 3 expected table files (MEDIUM #14).
    ValueError
        If ``standard_dir / "scraped"`` is absent or contains zero month
        directories (MEDIUM #14); on pre-dedup PK overlap (Pitfall 6); on
        column-set mismatch before reindex (HIGH #9); on hard integrity
        violations -- duplicate PK, FK orphan, OR entry/result horse_race_id
        1-to-1 mismatch (HIGH #8b cycle-4); on unexpected audit leakage.
    TypeError
        If a column cannot be coerced to its target dtype during recast.

    Notes
    -----
    The transform is IDEMPOTENT (HIGH #5). Kaggle is read from
    ``kaggle_input_dir`` (a stable separate input); scraped partitions are
    immutable inputs. A second invocation against the same inputs produces
    byte-identical output, fully recovering from any partial swap left by a
    mid-swap crash (HIGH #6 validate-before-swap with idempotent recovery via
    the DEDICATED ``_commit_staging`` swap function).
    """
    standard_dir = Path(standard_dir)
    if kaggle_input_dir is None:
        kaggle_input_dir = standard_dir / "kaggle"
    kaggle_input_dir = Path(kaggle_input_dir)

    logger.info(
        f"integrate_standard_layer: starting "
        f"(standard_dir={standard_dir!s}, kaggle_input_dir={kaggle_input_dir!s})"
    )

    # ----- MEDIUM #14: validate scraped input exists with >=1 month -----
    scraped_root = standard_dir / "scraped"
    if not scraped_root.exists():
        raise ValueError(
            f"integrate_standard_layer: scraped root {scraped_root!s} does not "
            f"exist; integration requires at least one scraped month partition"
        )
    month_dirs = sorted(p for p in scraped_root.iterdir() if p.is_dir())
    if not month_dirs:
        raise ValueError(
            f"integrate_standard_layer: scraped root {scraped_root!s} contains "
            f"zero month directories; integration requires scraped data"
        )

    # ----- Build merged frames per table -----
    merged_by_table: dict[str, pd.DataFrame] = {}

    for table, schema in SCHEMA_BY_TABLE.items():
        pk = PK_BY_TABLE[table]
        canonical_cols = list(schema.model_fields.keys())

        # HIGH #5: Kaggle read from SEPARATE input path, NOT output path.
        kaggle_path = kaggle_input_dir / f"{table}.parquet"
        if not kaggle_path.exists():
            raise FileNotFoundError(
                f"integrate_standard_layer: Kaggle input missing: {kaggle_path!s} "
                f"(table={table!r})"
            )
        kaggle_df = pd.read_parquet(kaggle_path, engine="pyarrow")

        # MEDIUM #14: per-month table file must exist.
        scraped_dfs: list[pd.DataFrame] = []
        for month_dir in month_dirs:
            month_table_path = month_dir / f"{table}.parquet"
            if not month_table_path.exists():
                raise FileNotFoundError(
                    f"integrate_standard_layer: scraped month {month_dir.name!r} "
                    f"lacks {table!r}.parquet at {month_table_path!s}"
                )
            scraped_dfs.append(pd.read_parquet(month_table_path, engine="pyarrow"))
        scraped_df = pd.concat(scraped_dfs, ignore_index=True) if scraped_dfs else pd.DataFrame(
            columns=canonical_cols
        )

        # HIGH #9: column-set equality BEFORE reindex.
        _assert_column_set_equality(kaggle_df, schema, f"kaggle[{table!r}]")
        _assert_column_set_equality(scraped_df, schema, f"scraped[{table!r}]")

        # Reindex to canonical column order, then recast to SCHEMA_DTYPE_MAP.
        kaggle_df = kaggle_df.reindex(columns=canonical_cols)
        scraped_df = scraped_df.reindex(columns=canonical_cols)
        kaggle_df = _recast_to_canonical(kaggle_df, schema)
        scraped_df = _recast_to_canonical(scraped_df, schema)

        merged = pd.concat([kaggle_df, scraped_df], ignore_index=True)

        # Pitfall 6: pre-dedup overlap RAISES (not silent drop_duplicates).
        if pk in merged.columns:
            dup_count = int(merged[pk].duplicated().sum())
            if dup_count > 0:
                overlapping = (
                    merged.loc[merged[pk].duplicated(keep=False), pk]
                    .dropna()
                    .unique()[:5]
                    .tolist()
                )
                raise ValueError(
                    f"integrate_standard_layer[{table!r}]: {dup_count} duplicate "
                    f"{pk!r} values post-concat -- unexpected Kaggle/scraped "
                    f"overlap; sample={overlapping}"
                )

        merged_by_table[table] = merged
        logger.info(
            f"integrate_standard_layer[{table!r}]: merged "
            f"{len(kaggle_df)} kaggle + {len(scraped_df)} scraped = "
            f"{len(merged)} rows"
        )

    merged_race = merged_by_table["race"]
    merged_entry = merged_by_table["entry"]
    merged_result = merged_by_table["result"]

    # ----- HIGH #8 + HIGH #8b cycle-4: validate_integrity + extended filter -----
    violations = validate_integrity(merged_race, merged_entry, merged_result)
    if violations:
        logger.warning(
            f"integrate_standard_layer: {len(violations)} integrity violation(s) "
            f"detected (hard violations raise below)"
        )
    # HIGH #8b: extended token set -- 'mismatch'/'1-to-1' catch the
    # 'horse_race_id mismatch: entry/result are not 1-to-1' violation string
    # at normalizer.py:330-334 which contains NEITHER 'duplicate' NOR 'orphan'.
    hard_violations = [
        v
        for v in violations
        if "duplicate" in v or "orphan" in v or "mismatch" in v or "1-to-1" in v
    ]
    if hard_violations:
        raise ValueError(
            f"integrate_standard_layer: {len(hard_violations)} hard integrity "
            f"violation(s) detected (duplicate PK / FK orphan / entry-result 1-to-1 "
            f"mismatch); refusing to write structurally inconsistent corpus. "
            f"First 3: {hard_violations[:3]}"
        )

    # ----- MEDIUM #13: audit_leakage CALLED on merged race + entry -----
    race_leaked = audit_leakage(
        [RaceSchema], merged_race, "post-integration race audit"
    )
    if race_leaked:
        raise ValueError(
            f"integrate_standard_layer: race audit leaked post-race columns "
            f"{race_leaked!r} (race must be pre-race only)"
        )
    entry_leaked = audit_leakage(
        [EntrySchema], merged_entry, "post-integration entry audit"
    )
    # popularity/win_odds are intentionally post-race per Phase 1 D-03 (Harville
    # EV proxy). Any OTHER leak is a hard error.
    expected_entry_leak = {"popularity", "win_odds"}
    unexpected_entry_leak = set(entry_leaked) - expected_entry_leak
    if unexpected_entry_leak:
        raise ValueError(
            f"integrate_standard_layer: entry audit leaked UNEXPECTED post-race "
            f"columns {sorted(unexpected_entry_leak)!r} "
            f"(expected only {sorted(expected_entry_leak)!r})"
        )
    # WR-03 (Phase 06 review): defense-in-depth — confirm the expected leaks
    # ARE present. _assert_column_set_equality (line 279-280) is the primary
    # guard for column presence and would catch a missing column first, but
    # this audit is documented as the last line of defense. If a future
    # refactor weakened the column-set equality check, a silent column drop
    # (e.g. popularity dropped from one input source) would otherwise go
    # undetected here. The expected leaks MUST be in the merged entry columns.
    missing_expected = expected_entry_leak - set(merged_entry.columns)
    if missing_expected:
        raise ValueError(
            f"integrate_standard_layer: entry table is MISSING expected "
            f"post-race columns {sorted(missing_expected)!r} (silent column "
            f"drop — popularity/win_odds must be present per Phase 1 D-03)"
        )

    # ----- HIGH #6 cycle-3 + cycle-5: validate-before-swap with idempotent recovery -----
    staging_dir = Path(
        tempfile.mkdtemp(prefix=".integration_staging_", dir=str(standard_dir))
    )
    try:
        # Stage all 3 merged frames via _atomic_write_parquet. NOTE:
        # _atomic_write_parquet's internal os.replace commits each STAGING file
        # BEFORE the swap loop; these staging commits are NOT routed through
        # _commit_staging and are NOT patched by the cycle-5 transactionality
        # test (which patches _commit_staging directly).
        for table, merged in merged_by_table.items():
            _atomic_write_parquet(merged, staging_dir / f"{table}.parquet")

        # Validate each staged file: row count > 0, schema column-set, PK unique.
        for table, schema in SCHEMA_BY_TABLE.items():
            staged_path = staging_dir / f"{table}.parquet"
            staged = pd.read_parquet(staged_path, engine="pyarrow")
            if len(staged) == 0:
                raise ValueError(
                    f"integrate_standard_layer[{table!r}]: staged file has 0 rows "
                    f"(expected > 0); aborting swap"
                )
            staged_cols = set(staged.columns)
            expected_cols = set(schema.model_fields.keys())
            if staged_cols != expected_cols:
                raise ValueError(
                    f"integrate_standard_layer[{table!r}]: staged column set "
                    f"diverges (extra={sorted(staged_cols - expected_cols)}, "
                    f"missing={sorted(expected_cols - staged_cols)}); aborting swap"
                )
            pk = PK_BY_TABLE[table]
            if pk in staged.columns:
                dup_count = int(staged[pk].duplicated().sum())
                if dup_count > 0:
                    raise ValueError(
                        f"integrate_standard_layer[{table!r}]: staged file has "
                        f"{dup_count} duplicate {pk!r}; aborting swap"
                    )

        # Only AFTER all staged files validate, swap into root via the
        # DEDICATED _commit_staging boundary (cycle-5).
        _commit_staging(staging_dir, standard_dir)
    finally:
        # Best-effort staging cleanup. On success the staging files have been
        # os.replace'd into root, so the staging dir is empty. On failure the
        # staging files remain and should be removed so a future run does not
        # pick them up.
        shutil.rmtree(staging_dir, ignore_errors=True)

    logger.info(
        f"integrate_standard_layer: complete -- wrote race/entry/result to "
        f"{standard_dir!s}"
    )

    return {
        "race": standard_dir / "race.parquet",
        "entry": standard_dir / "entry.parquet",
        "result": standard_dir / "result.parquet",
        "audit": {
            "race": race_leaked,
            "entry": entry_leaked,
        },
    }


